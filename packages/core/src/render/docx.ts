import {
  AlignmentType,
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
} from "docx";
import type { SectionId } from "../schema/index";
import type { Locale } from "../schema/locale";
import { t } from "../schema/locale";
import type { LocaleFile } from "../locale/types";
import { formatDateRange, formatYearRange } from "../resolve/dates";
import { visibleSections, type ResumeData } from "../resolve/index";

/**
 * DOCX renderer. ATS-parseable by construction: real heading styles,
 * native bullet lists, single column, no tables or text boxes.
 *
 * Heading hierarchy mirrors the HTML resumes:
 * name → Title, sections → Heading1, entries → Heading2.
 */

function heading(text: string, level: (typeof HeadingLevel)[keyof typeof HeadingLevel]): Paragraph {
  return new Paragraph({ heading: level, text, spacing: { before: 240, after: 80 } });
}

function body(text: string, opts: { italics?: boolean; spacingAfter?: number } = {}): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text, italics: opts.italics ?? false })],
    spacing: { after: opts.spacingAfter ?? 80 },
  });
}

function bullet(text: string): Paragraph {
  return new Paragraph({ text, bullet: { level: 0 }, spacing: { after: 40 } });
}

const sectionBody: Record<SectionId, (r: ResumeData, locale: LocaleFile, lang: Locale) => Paragraph[]> = {
  summary: (r, _locale, lang) => [body(t(r.summary, lang))],

  experience: (r, locale, lang) =>
    r.experience.flatMap((role) => {
      const meta = [
        formatDateRange(role.start, role.end, locale),
        role.location,
        locale.employment_types[role.employment_type],
      ]
        .filter(Boolean)
        .join(" · ");
      return [
        heading([t(role.title, lang), t(role.company, lang)].filter(Boolean).join(" — "), HeadingLevel.HEADING_2),
        body(meta, { italics: true }),
        ...role.bullets.map((b) => bullet(t(b.text, lang))),
      ];
    }),

  projects: (r, locale, lang) =>
    r.projects.flatMap((project) => {
      const layout = r.template.project_layout;
      const paragraphs = [heading(project.name, HeadingLevel.HEADING_2), body(t(project.tagline, lang), { italics: true })];
      if (layout !== "compact") {
        paragraphs.push(body(t(project.description, lang)));
      }
      paragraphs.push(...project.highlights.map((h) => bullet(t(h.text, lang))));
      if (project.technologies.length > 0) {
        paragraphs.push(
          layout === "compact"
            ? body(project.technologies.join(" · "))
            : body(`${locale.resume.technologies}: ${project.technologies.join(", ")}`),
        );
      }
      if (layout !== "compact" && project.links.length > 0) {
        paragraphs.push(body(`${locale.resume.links}: ${project.links.map((l) => `${t(l.label, lang)} (${l.url})`).join(" · ")}`));
      }
      return paragraphs;
    }),

  skills: (r, _locale, lang) =>
    r.skills.map((c) => bullet(`${t(c.category, lang)}: ${c.items.map((i) => t(i.name, lang)).join(", ")}`)),

  education: (r, locale, lang) =>
    r.education.flatMap((edu) => [
      heading(`${t(edu.degree, lang)} ${t(edu.field, lang)} — ${edu.institution}`, HeadingLevel.HEADING_2),
      body(`${formatYearRange(edu.start, edu.end, locale)} · ${edu.location}`, { italics: true }),
      ...edu.highlights.map((h) => bullet(t(h, lang))),
    ]),

  languages: (r, locale, lang) => r.languages.map((l) => bullet(`${t(l.name, lang)} — ${locale.proficiency_levels[l.proficiency]}`)),
};

export async function renderDocx(resume: ResumeData, locale: LocaleFile, lang: Locale): Promise<Buffer> {
  const { profile: p } = resume;

  const children: Paragraph[] = [
    new Paragraph({
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.LEFT,
      children: [new TextRun({ text: p.name, bold: true })],
      spacing: { after: 40 },
    }),
    body(t(resume.title, lang)),
    body(p.location),
    body([p.email, p.linkedin, p.github].join(" · ")),
    body([p.website, p.cv].join(" · "), { spacingAfter: 200 }),
  ];

  for (const section of visibleSections(resume)) {
    children.push(heading(locale.sections[section], HeadingLevel.HEADING_1));
    children.push(...sectionBody[section](resume, locale, lang));
  }

  const doc = new Document({
    creator: p.name,
    title: `${p.name} — ${t(resume.title, lang)}`,
    description: `Resume (${t(resume.template.name, lang)}) generated by career-os`,
    sections: [{ children }],
  });

  return Packer.toBuffer(doc);
}
